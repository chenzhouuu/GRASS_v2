"""Scenario Interpreter — before/after comparison (P2, deterministic).

Computes the baseline-vs-scenario comparison from two OptimizationRun snapshots:
direction-aware KPI deltas, binding-constraint shift, an objective waterfall
Plotly spec, and a narrative ("why it changed"). All math is deterministic; the
narrative is rule-generated by default and optionally refined by an LLM.

Used by the ScenarioRunner to populate ``scenario_comparison`` state, which the
frontend ScenarioComparisonCard renders.
"""

from __future__ import annotations

import logging

from ..core.schemas import KpiDelta, OptimizationRun, Scenario, ScenarioComparison

logger = logging.getLogger(__name__)

# Theme-matched colors (GRASS tokens) for the waterfall.
_C_UP = "#e11d48"      # objective increased
_C_DOWN = "#059669"    # objective decreased
_C_TOTAL = "#0f766e"   # endpoints
_C_CONNECT = "#94a3b8"

# Substring → favorable direction. "objective_value" handled separately by sense.
_DOWN_HINTS = ("cost", "distance", "dist", "utilization", "util", "emission", "risk", "lateness", "shortfall")
_UP_HINTS = ("served", "service", "fill", "coverage", "throughput", "profit", "revenue", "margin")


def good_direction(kpi_name: str, objective_sense: str) -> str:
    """Heuristic: which direction is favorable for a KPI (drives UI coloring)."""
    n = kpi_name.lower()
    if n == "objective_value":
        return "down" if objective_sense == "minimize" else "up"
    if any(h in n for h in _DOWN_HINTS):
        return "down"
    if any(h in n for h in _UP_HINTS):
        return "up"
    return "flat"


def build_kpi_deltas(
    baseline: OptimizationRun, scenario: OptimizationRun, objective_sense: str
) -> list[KpiDelta]:
    """Join KPIs present in both runs into direction-aware deltas."""
    base_map = {k.name: k for k in baseline.kpis}
    deltas: list[KpiDelta] = []
    for sk in scenario.kpis:
        bk = base_map.get(sk.name)
        if bk is None:
            continue
        d = sk.value - bk.value
        pct = (d / bk.value * 100.0) if bk.value else None
        deltas.append(
            KpiDelta(
                name=sk.name,
                baseline=bk.value,
                scenario=sk.value,
                delta=d,
                pct=pct,
                unit=sk.unit or "",
                good_direction=good_direction(sk.name, objective_sense),
            )
        )
    return deltas


def build_binding_shift(
    baseline: OptimizationRun, scenario: OptimizationRun
) -> tuple[list[str], list[str]]:
    """Return (newly_binding, no_longer_binding)."""
    b = set(baseline.binding_constraints)
    s = set(scenario.binding_constraints)
    return sorted(s - b), sorted(b - s)


def build_waterfall_spec(
    base_obj: float | None, scen_obj: float | None
) -> dict | None:
    """Plotly waterfall: Baseline → Δ → Scenario (numeric-direction colored)."""
    if base_obj is None or scen_obj is None:
        return None
    d = scen_obj - base_obj
    return {
        "data": [
            {
                "type": "waterfall",
                "orientation": "v",
                "measure": ["absolute", "relative", "total"],
                "x": ["Baseline", "Δ", "Scenario"],
                "y": [base_obj, d, None],
                "text": [f"{base_obj:,.0f}", f"{d:+,.0f}", f"{scen_obj:,.0f}"],
                "textposition": "outside",
                "connector": {"line": {"color": _C_CONNECT}},
                "increasing": {"marker": {"color": _C_UP}},
                "decreasing": {"marker": {"color": _C_DOWN}},
                "totals": {"marker": {"color": _C_TOTAL}},
            }
        ],
        "layout": {
            "title": {"text": "Objective change: baseline → scenario"},
            "showlegend": False,
            "height": 300,
            "margin": {"l": 60, "r": 20, "t": 40, "b": 36},
            "paper_bgcolor": "transparent",
            "plot_bgcolor": "transparent",
        },
    }


def build_tornado_spec(results: list[dict], base_objective: float | None) -> dict | None:
    """One-factor sensitivity tornado from sweep results (P3).

    ``results``: list of {factor, low_obj, high_obj}. Bars show Δ-objective vs
    baseline at the factor's low/high setting; sorted so the widest swing is on
    top. Deterministic Plotly horizontal-bar spec.
    """
    if base_objective is None:
        return None
    rows = [r for r in results if r.get("low_obj") is not None or r.get("high_obj") is not None]
    if not rows:
        return None

    def _delta(obj):
        return (obj if obj is not None else base_objective) - base_objective

    def _swing(r):
        return abs(_delta(r.get("low_obj"))) + abs(_delta(r.get("high_obj")))

    rows = sorted(rows, key=_swing)  # ascending → widest at top in a horizontal bar
    factors = [r["factor"] for r in rows]
    low = [_delta(r.get("low_obj")) for r in rows]
    high = [_delta(r.get("high_obj")) for r in rows]
    return {
        "data": [
            {"type": "bar", "orientation": "h", "y": factors, "x": low, "name": "low",
             "marker": {"color": _C_DOWN}},
            {"type": "bar", "orientation": "h", "y": factors, "x": high, "name": "high",
             "marker": {"color": _C_UP}},
        ],
        "layout": {
            "barmode": "overlay",
            "title": {"text": "Objective sensitivity (tornado)"},
            "xaxis": {"title": {"text": "Δ objective vs baseline"}, "zeroline": True},
            "yaxis": {"automargin": True},
            "height": max(260, len(factors) * 42 + 120),
            "showlegend": True,
            "paper_bgcolor": "transparent",
            "plot_bgcolor": "transparent",
            "margin": {"l": 120, "r": 20, "t": 40, "b": 40},
        },
    }


def build_narrative(c: ScenarioComparison) -> str:
    """Deterministic 'why it changed' summary from the comparison data."""
    parts: list[str] = []
    if c.objective_baseline is not None and c.objective_scenario is not None:
        d = c.objective_scenario - c.objective_baseline
        pct = (d / c.objective_baseline * 100.0) if c.objective_baseline else 0.0
        verb = "rose" if d > 0 else "fell" if d < 0 else "was unchanged"
        label = c.scenario_name or "the scenario"
        parts.append(f"Under {label}, the objective {verb} {abs(pct):.1f}% ({d:+,.0f}).")
    if c.binding_added:
        parts.append(
            "Newly binding: " + ", ".join(c.binding_added) + " — the bottleneck shifted here."
        )
    if c.binding_removed:
        parts.append("No longer binding: " + ", ".join(c.binding_removed) + ".")
    notable = [
        k for k in c.kpi_deltas
        if k.name != "objective_value" and k.pct is not None and abs(k.pct) >= 5.0
    ]
    if notable:
        bits = [f"{k.name} {k.pct:+.1f}%" for k in notable[:3]]
        parts.append("Notable shifts: " + ", ".join(bits) + ".")
    return " ".join(parts) or "No material change versus the baseline."


def _llm_narrative(model, comparison: ScenarioComparison) -> str | None:
    """Optional LLM refinement of the narrative (best-effort)."""
    from langchain_core.messages import HumanMessage, SystemMessage

    deltas = "; ".join(
        f"{k.name}: {k.baseline:,.2f}→{k.scenario:,.2f} ({k.pct:+.1f}%)" if k.pct is not None
        else f"{k.name}: {k.baseline:,.2f}→{k.scenario:,.2f}"
        for k in comparison.kpi_deltas
    )
    prompt = (
        "You are a supply-chain optimization analyst. In 2-3 sentences, explain WHY the "
        "scenario outcome differs from the baseline, in business terms. Be concrete and "
        "reference the binding-constraint shift if present. Do not restate every number.\n\n"
        f"Scenario: {comparison.scenario_name} — {comparison.scenario_description}\n"
        f"Objective ({comparison.objective_sense}): "
        f"{comparison.objective_baseline} → {comparison.objective_scenario}\n"
        f"KPI deltas: {deltas}\n"
        f"Newly binding: {comparison.binding_added or 'none'}\n"
        f"No longer binding: {comparison.binding_removed or 'none'}"
    )
    resp = model.invoke([
        SystemMessage(content="You explain optimization what-if results crisply."),
        HumanMessage(content=prompt),
    ])
    text = getattr(resp, "content", None)
    return text.strip() if isinstance(text, str) and text.strip() else None


def build_comparison(
    baseline: OptimizationRun,
    scenario_run: OptimizationRun,
    scenario: Scenario,
    model=None,
) -> ScenarioComparison:
    """Assemble the full baseline-vs-scenario comparison (deterministic + optional LLM)."""
    sense = "minimize"
    if baseline.formulation and baseline.formulation.objective:
        sense = baseline.formulation.objective.sense

    comp = ScenarioComparison(
        baseline_run_id=baseline.run_id,
        scenario_run_id=scenario_run.run_id,
        scenario_name=scenario.name,
        scenario_description=scenario.description,
        objective_sense=sense,
        objective_baseline=baseline.objective,
        objective_scenario=scenario_run.objective,
        kpi_deltas=build_kpi_deltas(baseline, scenario_run, sense),
        binding_added=build_binding_shift(baseline, scenario_run)[0],
        binding_removed=build_binding_shift(baseline, scenario_run)[1],
        waterfall=build_waterfall_spec(baseline.objective, scenario_run.objective),
    )
    comp.narrative = build_narrative(comp)
    if model is not None:
        try:
            refined = _llm_narrative(model, comp)
            if refined:
                comp.narrative = refined
        except Exception as exc:  # narrative is best-effort; never fail the comparison
            logger.warning("LLM narrative refinement failed: %s", exc)
    return comp


# ── structural (Layer 1) comparison ──────────────────────────────────


def _structural_narrative(
    scenario: Scenario, impact: dict, trace: dict | None, alternatives: dict | None
) -> str:
    """Rule-generated narrative for a graph-overlay structural scenario."""
    removed = ", ".join(
        f"{ed['label']} {ed['name'] or ed['id']}" for ed in impact.get("edits", [])
    )
    lines = [f"Structural scenario: {removed} removed from the network."]

    for row in impact.get("echelons", []):
        if row["connected_drop"] > 0 and not row["removed"]:
            lines.append(
                f"{row['echelon']}: {row['connected_drop']} of "
                f"{row['baseline_connected']} previously connected entities lose "
                f"their full supply-chain path."
            )
    if len(lines) == 1:
        lines.append(
            "No surviving entity loses its full supply-chain path — the network "
            "has redundant routes around the removed entities."
        )

    hops = [
        f"{f['echelon']} at hop {f['hop']} ({f['count']} affected)"
        for f in (trace or {}).get("frontier", [])
        if f["direction"] == "downstream"
    ]
    if hops:
        lines.append("Downstream exposure: " + "; ".join(hops) + ".")

    for group in (alternatives or {}).get("alternatives", []):
        partners = group.get("partners") or []
        if partners and partners[0].get("alternatives"):
            first = partners[0]
            alt = first["alternatives"][0]
            lines.append(
                f"Nearest alternative {group['removed_label']} for the "
                f"{len(partners)} affected {group['partner_echelon']} partners: "
                f"e.g. {first['partner']} → {alt['name']} "
                f"({alt['distance_miles']} mi)."
            )
    return " ".join(lines)


def build_structural_comparison(
    scenario: Scenario,
    impact: dict,
    trace: dict | None = None,
    alternatives: dict | None = None,
) -> ScenarioComparison:
    """Comparison for a graph-overlay scenario: per-echelon connectivity KPIs.

    No optimization run is involved — baseline numbers come from the unfiltered
    graph, scenario numbers from the same queries with the removals applied.
    """
    kpi_deltas: list[KpiDelta] = []
    for row in impact.get("echelons", []):
        base = float(row["baseline_connected"])
        scen = float(row["scenario_connected"])
        kpi_deltas.append(KpiDelta(
            name=f"connected_{row['echelon']}",
            baseline=base,
            scenario=scen,
            delta=scen - base,
            pct=((scen - base) / base * 100.0) if base else None,
            unit="",
            good_direction="up",
        ))
    return ScenarioComparison(
        baseline_run_id="graph-baseline",
        scenario_run_id=scenario.scenario_id,
        scenario_name=scenario.name,
        scenario_description=scenario.description,
        kpi_deltas=kpi_deltas,
        narrative=_structural_narrative(scenario, impact, trace, alternatives),
    )


